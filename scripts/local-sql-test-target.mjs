// libpq accepts hostaddr/service/options outside the URI authority. Local test
// commands must not inherit a connection route or transaction setting from them.
export function localSqlEnvironment(source = process.env) {
  return {
    ...Object.fromEntries(
      Object.entries(source).filter(([name]) => !/^PG/i.test(name) && name !== "PSQL_BIN"),
    ),
    PGCONNECT_TIMEOUT: "10",
    PGAPPNAME: "careconnect-disposable-sql-test",
  };
}

export function assertLocalDatabaseUrl(value) {
  let parsed;
  try {
    parsed = new URL(value);
  } catch {
    throw new Error("Refusing to run: invalid local database URL.");
  }
  if (
    !["postgres:", "postgresql:"].includes(parsed.protocol) ||
    !["127.0.0.1", "[::1]"].includes(parsed.hostname) ||
    parsed.port !== "54322" ||
    parsed.pathname !== "/postgres" ||
    parsed.search ||
    parsed.hash
  ) {
    throw new Error(
      "Refusing to run: expected a loopback database URL without connection overrides.",
    );
  }
  return value;
}

// Keep test connections on the port generated by `supabase init`; a different
// loopback PostgreSQL listener is not proof of the disposable Supabase stack.
export function localPsqlCommand(platform = process.platform) {
  // GitHub's Ubuntu runner installs the client at this fixed system path. Avoid
  // resolving a database command through PATH in the isolated CI workflow.
  return platform === "linux" ? "/usr/bin/psql" : "psql";
}

const safeSqlStates = new Set([
  "42501",
  "23505",
  "23503",
  "23514",
  "40001",
  "40P01",
  "42601",
  "0A000",
  "42P01",
  "42703",
]);

// Direct local runner failures must not print libpq's raw diagnostics, which may
// include the connection URL. CI has its own allow-listed summary path.
export function safeSqlFailure(command, status, detail = "") {
  const label =
    command === "psql" ? "psql" : command === "supabase" ? "Supabase CLI" : "Local SQL command";
  const exit = Number.isInteger(status) ? `exit ${status}` : "could not start";
  const match = detail.match(/SQLSTATE:?\s*(\d{5})/i);
  const state = match && safeSqlStates.has(match[1]) ? ` SQLSTATE ${match[1]}.` : "";
  return `${label} ${exit}.${state} Raw SQL diagnostics were withheld.`;
}
